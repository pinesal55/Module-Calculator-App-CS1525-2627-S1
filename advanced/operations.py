def add(number_1: float, number_2: float) -> float:
    """
    Add two numbers together
    :param number_1: The first number.
    :param number_2: The second number.
    :return:
    float: The sum of number_1 and number_2.
    """
    return number_1 + number_2

def subtract(number_1: float, number_2: float) -> float:
    """
    Subtract two numbers together
    :param number_1: The first number.
    :param number_2: The second number.
    :return:
    float: The difference of number_1 and number_2.
    """
    return number_1 - number_2

def multiply(number_1: float, number_2: float) -> float:
    """
    Multiply two numbers together
    :param number_1: The first number.
    :param number_2: The second number.
    :return:
    float: The product of number_1 and number_2.
    """
    return number_1 * number_2

def divide(number_1: float, number_2: float) -> float:
    """
    Divide two numbers together
    :param number_1: The number to be divided. (Dividend)
    :param number_2: The number to divide by. (Divisor)
    :return:
    float: The result of number_1 and number_2.
    """
    return number_1 / number_2